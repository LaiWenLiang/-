#ifndef __APP_POWER_H
#define __APP_POWER_H

/***************************************************************************************************
 * 应用层省电管理（层级一）
 * 连续 POWER_SAVE_TIMEOUT_MS 没有任何活动（UWB 帧 / 按键 / 遥控指令），
 * 就进入省电态：停车 + 关 OLED + 关 ESP8266（省约 70mA）+ 停发电机心跳；
 * 任何活动（UWB 收到数据 / 按任意键）立即唤醒恢复。
 ***************************************************************************************************/

#define POWER_SAVE_TIMEOUT_MS   300000   /* 空闲 5 分钟进省电态，可按需改小测试 */

/* 有活动时调用（UWB 解析任务、按键扫描处），刷新空闲计时 */
void Power_FeedAlive(void);

/* 省电管理任务（FreeRTOS 任务函数，1 秒周期） */
void App_Power_Task(void *param);

#endif /* __APP_POWER_H */
